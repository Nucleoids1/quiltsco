Quiltsco FAQ
<br /><br />
Here, you can find the answer to all your message board questions
<br /><br />
Q: How do I post?
<br /><br />
A: Simple, at the bottom of the screen, there's space for you to write. Just write your reply, then click on "Post Reply". Same goes for a new thread, you just got to add the thread's name.
<br /><br />
Q: How do I post a pic?
<br /><br />
A: They are two ways to do this. First, if your pic is on a ravewave gallery, just enter the image's code. Here's an example. [58255].
<br /><br />
If your pic isn't on quiltsco.com, do it like this. [img]http://www.website.com/mypic.jpg[/img]. If your pic isn't hosted on the internet, you can do it using this website. https://www.imageshack.us/, you can also just host it on quiltsco.com, in your pictures.
<br /><br />
Q: How do I quote someone?
<br /><br />
A: Next to every post, there's an icon that says "quote message". Click on it. You should now see the complete post on your reply box down the screen. Just deleate what you don't wanna quote, and Voilà!
<br /><br />
Q: And what about smileys?
<br /><br />
A: Of course, you can use smileys. when you're viewing a forum, and you see all the threads listed, you should also see another icon on the top right of the screen that says "Smileys". Click on it. You'll see a list of the smileys available on quiltsco.com. Here's a direct link. http://www.quiltsco.com/?s=smileys Next to each smiley is the code you need to enter if you wanna use this particular emoticon. They're pretty easy to remember. You can always open the smiley page in a new window if you have a hard time remembering them.
<br /><br />
Q: And what about bold characters, can I underline text?
<br /><br />
A: Simple enough, choose the text you want to have in bold characters, and add [b] at the beginning of it. Then, add [/b] at the end. Again, you guessed it, minus the space. [i] and [/i] is for italics. Underline uses [u] and [/u]
<br /><br />
Q: And what about videos?
<br /><br />
A: Simple enough also! [video]http://www.youtube.com/v/CODE[/video]
<br /><br />
Q: And what about those ratings things?
<br /><br />
A: Start by opening a thread. You should see on the top right of the screen a little box. If you open it, you'll see a list of words that could define a thread, things like "Funny", "Boring" or "Flame War". Just choose the one you think best describes the thread. You don't need to hit enter or anything, your rating will be saved automatically. People won't be able to know how you're rated a particular thread, it will only affect the overall rating, wich appears next to the thread's name. This is what quiltsco.com uses opening it.
<br /><br />
You can also rate individual posts. Next to every post, you'll see "good/bad". Just click on the one you think best describes the post. If a post gets too many bad ratings, people won't be able to see it, unless they click on "toggle reply". YOu can also use that to hide a reply, if you don't want to see it, even if this reply didn't get a bad rating. Of course, you can't rate your own posts or threads.
<br /><br />
Q: One last thing, If I'm at work, anything I can do to hide the "not work safe" content?
<br /><br />
A: As a matter of facts, yes you can. Wherever you are on the site, you can see "Ratings: Normal View" on the top right corner. Simply switch "Normal View" for "Safe Content". This way, porn and other unsafe material will be hidden from you.

